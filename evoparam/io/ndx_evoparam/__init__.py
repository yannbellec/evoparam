"""The ``ndx-evoparam`` NWB extension (spec §10.3, REQ-318).

Types (namespace ``ndx-evoparam``, version 0.1.0):

* ``EvokedResponseFitTable`` (DynamicTable): the fitted components;
* ``ResponseTestTable`` (DynamicTable): the existence tests;
* ``TrialFitTable`` (DynamicTable): the trial-by-trial parameters;
* ``StimulationEventsTable`` (EventsTable): stimulation events with ``stim_site``,
  ``stim_current`` (A), ``stim_pulse_width`` (s), ``stim_polarity``, ``stim_n_pulses`` and
  ``stim_frequency`` (Hz);
* ``ResponseFitSettings`` (LabMetaData): ``settings_json``, ``provenance_json``,
  ``package_version``, ``preset_name``, ``preset_version``.

The YAML files of ``spec/`` are generated by :func:`build_spec` (run
``python -m evoparam.io.ndx_evoparam`` after changing the types); files written with the
extension cache the specification, so any NWB reader can open them. Publishing the
extension to PyPI and to the NDX catalog is a release step (RELEASING.md).
"""

