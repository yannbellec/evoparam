"""Markdown report of benchmark results (spec §8.4; the report of REQ-353).

The report is built from the signed result documents only (their signatures are checked);
every number in it is a metric of a result file, formatted by :func:`format_metric`.
"""

import glob
import os

from evoparam.errors import DataError

from .scoring import HEADLINE, read_result
from .tasks import TASKS

__all__ = ["load_results", "format_metric", "metric_label", "markdown", "write_report"]

# Metrics in seconds shown in milliseconds.
_MS = (
    "latency_mae",
    "latency_bias",
    "time_centroid_error",
    "n1_latency_error",
    "peak_latency.mae_vs_truth",
    "fractional_area_latency.mae_vs_truth",
    "peak_latency.mae_vs_definition",
    "fractional_area_latency.mae_vs_definition",
)
LABELS = {
    "auc": "AUC",
    "f1": "F1",
    "fpr_at_0.05": "FPR at 0.05",
    "ks_uniform": "KS (null p)",
    "reported_fraction": "reported",
    "coverage_latency": "latency coverage",
    "amplitude_rel_mae": "amplitude rel. MAE",
    "false_rate_empty": "false rate (empty)",
    "artifact_residual_rel": "residual / artifact",
    "artifact_residual_rms": "residual RMS (uV)",
    "response_rmse_50ms": "response RMSE 0-50 ms (uV)",
    "latency_r": "latency r",
    "amplitude_r": "amplitude r",
    "jitter_sd_rel_error": "jitter SD rel. error",
    "recovery_rate": "zone recovery",
    "freq_centroid_rel_error": "freq. centroid rel. error",
    "type_i_error": "type I error",
}


def metric_label(name):
    """Column title of a metric (unit in ms for latencies)."""
    label = LABELS.get(name, name.replace("_", " "))
    return f"{label} (ms)" if name in _MS else label


def format_metric(name, value):
    """Return the text of a metric value.

    ``n/a`` for None, latencies in ms, 4 significant digits.
    """
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, int):
        return str(value)
    if name in _MS:
        value = value * 1000.0
    return f"{value:.4g}"


def load_results(folder):
    """Load every result document of a folder (``*.json``), signatures checked.

    The documents are sorted by task then method name and version.
    """
    paths = sorted(glob.glob(os.path.join(folder, "*.json")))
    if not paths:
        raise DataError(f"{folder}: no result file (*.json).")
    docs = [read_result(p) for p in paths]
    return sorted(
        docs, key=lambda d: (d["task"], d["method"]["name"], str(d["method"].get("version", "")))
    )


def _suites(docs):
    return sorted(
        {(d["suite"]["name"], d["suite"]["version"], d["suite"]["sha256"]) for d in docs}
    )


def markdown(docs):
    """Return the report text."""
    suites = _suites(docs)
    lines = ["# evoparam benchmark report", ""]
    lines.append(
        "Generated by `evoparam.benchmark.report` from "
        f"{len(docs)} signed result files (signatures checked); no number is "
        "written by hand. Package version(s): "
        + ", ".join(sorted({d["package"]["version"] for d in docs}))
        + "."
    )
    lines.append("")
    for name, version, digest in suites:
        lines.append(f"- suite `{name}` {version} (SHA-256 of the suite file `{digest}`)")
    lines.append("")
    for task in TASKS:
        rows = [d for d in docs if d["task"] == task]
        if not rows:
            continue
        lines += [f"## {task}: {TASKS[task]}", ""]
        heads = HEADLINE[task]
        lines.append(
            "| method | version | cells | " + " | ".join(metric_label(h) for h in heads) + " |"
        )
        lines.append("|" + "---|" * (3 + len(heads)))
        for d in rows:
            n_cells = sum(1 for c in d["cells"] if "metrics" in c)
            values = [format_metric(h, d["headline"].get(h)) for h in heads]
            lines.append(
                f"| {d['method']['name']} | {d['method'].get('version', '')} | "
                f"{n_cells} | " + " | ".join(values) + " |"
            )
        lines.append("")
        missing = [(d["method"]["name"], c) for d in rows for c in d["missing_cells"]]
        if missing:
            lines.append(
                "Cells without output: " + ", ".join(f"{m} {c}" for m, c in missing) + "."
            )
            lines.append("")
    lines += ["## Methods", ""]
    seen = {}
    for d in docs:
        seen.setdefault((d["method"]["name"], str(d["method"].get("version", ""))), d["method"])
    for (name, version), method in sorted(seen.items()):
        settings = ", ".join(
            f"{k}={v}"
            for k, v in sorted(method.get("settings", {}).items())
            if v not in (None, {}, [])
        )
        lines.append(
            f"- **{name}** {version}: {method.get('description', '')}"
            + (f" Settings: {settings}." if settings else "")
            + (f" Citation: {method['citation']}." if method.get("citation") else "")
        )
    lines.append("")
    return "\n".join(lines)


def write_report(results_folder, path):
    """Write the Markdown report of the results of a folder; returns the path."""
    text = markdown(load_results(results_folder))
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fobj:
        fobj.write(text)
    return path
