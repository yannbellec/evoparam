"""Static leaderboard page generated from result JSONs only (spec §8.4, REQ-357).

``write_leaderboard(results_folder, path)`` reads the signed result documents of a folder
(signatures checked, so a hand-edited number is refused), and writes one self-contained
HTML page (no server, no script, no external resource): one table per task, one row per
method x version, with the headline metrics of :data:`~evoparam.benchmark.scoring.HEADLINE`,
the method's citation and the first characters of the result's signature. The page depends
only on the result files: the same files give the same bytes. Entries are accepted by pull
request with the result JSON and the code or container that produced it.
"""

import html
import os

from .report import format_metric, load_results, metric_label
from .scoring import HEADLINE
from .tasks import TASKS

__all__ = ["leaderboard_html", "write_leaderboard"]

STYLE = """
:root { color-scheme: light dark; --fg: #1d1d1f; --bg: #ffffff; --line: #d0d0d5;
        --head: #f2f2f5; --muted: #5f5f66; }
@media (prefers-color-scheme: dark) {
  :root { --fg: #ececf0; --bg: #17171a; --line: #3a3a40; --head: #222227; --muted: #a3a3ad; }
}
body { font: 15px/1.45 system-ui, -apple-system, "Segoe UI", sans-serif; color: var(--fg);
       background: var(--bg); margin: 0 auto; max-width: 1100px; padding: 16px; }
h1 { font-size: 1.5em; margin: 0.4em 0; } h2 { font-size: 1.15em; margin-top: 1.6em; }
p.meta { color: var(--muted); }
div.scroll { overflow-x: auto; }
table { border-collapse: collapse; width: 100%; font-variant-numeric: tabular-nums; }
th, td { border-bottom: 1px solid var(--line); padding: 4px 8px; text-align: right;
         white-space: nowrap; }
th { background: var(--head); } td.l, th.l { text-align: left; }
td.cite { white-space: normal; text-align: left; color: var(--muted); font-size: 0.9em; }
code { font-size: 0.9em; }
""".strip()


def leaderboard_html(docs):
    """The page for a list of result documents."""

    esc = html.escape
    suites = sorted({(d["suite"]["name"], d["suite"]["version"]) for d in docs})
    out = ["<!doctype html>", '<html lang="en">', "<head>", '<meta charset="utf-8">',
           '<meta name="viewport" content="width=device-width, initial-scale=1">',
           "<title>evoparam benchmark leaderboard</title>", f"<style>\n{STYLE}\n</style>",
           "</head>", "<body>", "<h1>evoparam benchmark leaderboard</h1>",
           '<p class="meta">Generated by <code>evoparam.benchmark.leaderboard</code> '
           f"from {len(docs)} signed result files; every number comes from "
           "a result file. Suites: "
           + ", ".join(f"<code>{esc(n)}</code> {esc(v)}" for n, v in suites) + ".</p>"]
    for task in TASKS:
        rows = [d for d in docs if d["task"] == task]
        if not rows:
            continue
        heads = HEADLINE[task]
        out.append(f'<h2 id="{task}">{task}: {esc(TASKS[task])}</h2>')
        out.append('<div class="scroll"><table>')
        out.append("<thead><tr><th class=\"l\">method</th><th class=\"l\">version</th>"
                   "<th class=\"l\">suite</th>"
                   + "".join(f"<th>{esc(metric_label(h))}</th>" for h in heads)
                   + "<th class=\"l\">citation</th><th class=\"l\">result</th></tr></thead>")
        out.append("<tbody>")
        for d in rows:
            method = d["method"]
            cells = "".join(f"<td>{esc(format_metric(h, d['headline'].get(h)))}</td>"
                            for h in heads)
            out.append(f"<tr><td class=\"l\">{esc(method['name'])}</td>"
                       f"<td class=\"l\">{esc(str(method.get('version', '')))}</td>"
                       f"<td class=\"l\">{esc(d['suite']['name'])} "
                       f"{esc(d['suite']['version'])}</td>{cells}"
                       f"<td class=\"cite\">{esc(method.get('citation', ''))}</td>"
                       f"<td class=\"l\"><code>{esc(d['signature']['digest'][:12])}</code>"
                       "</td></tr>")
        out.append("</tbody></table></div>")
    out += ["</body>", "</html>", ""]
    return "\n".join(out)


def write_leaderboard(results_folder, path):
    """Write the page of the results of a folder; returns the path."""

    text = leaderboard_html(load_results(results_folder))
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fobj:
        fobj.write(text)
    return path
