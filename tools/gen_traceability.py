"""Regenerate the requirement → test traceability report (spec §14.2, REQ-399).

For every requirement of the matrix of §14.2 (``| REQ-NNN | section | module | test files |
validation |``) the report records the test files the matrix names (spec paths ``tests/...``
are ``evoparam/tests/...`` here), whether they exist, and the test files of the repository
that name the requirement (``REQ-NNN`` or ``reqNNN`` in a test name, a docstring or a
comment of ``evoparam/tests``, or of the test files of ``benchmarks`` and ``validation``).
A requirement that no test names is **untested**.

The report is regenerated at each release and attached to the release artefacts (the
``release`` workflow writes ``dist/traceability.json``); it is not kept in the repository,
since every new test changes it. ``evoparam/tests/test_soup_inventory.py`` checks the
generator and lists the untested requirements. Exit code 1 when a requirement is untested.

Usage::

    python tools/gen_traceability.py [--out dist/traceability.json]
"""

import argparse
import ast
import io
import json
import pathlib
import re
import sys
import tokenize

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "docs" / "spec" / "SPEC.md"
TEST_ROOTS = ("evoparam/tests", "benchmarks", "validation")


def matrix(spec_text):
    """[(REQ id, section, module, [spec test paths])] of §14.2."""
    body = spec_text.split("### 14.2", 1)[1]
    rows = []
    for line in body.splitlines():
        match = re.match(r"^\| (REQ-\d{3}) \| ([^|]*) \| ([^|]*) \| ([^|]*) \|", line)
        if match:
            rows.append(
                (
                    match.group(1),
                    match.group(2).strip(),
                    match.group(3).strip(),
                    re.findall(r"`([^`]+\.py)[^`]*`", match.group(4)),
                )
            )
    return rows


def _repo_path(spec_path):
    path = spec_path.split("::")[0]
    return "evoparam/" + path if path.startswith("tests/") else path


def _named(text):
    """Return the requirement numbers a test file names.

    Only its test names, docstrings and comments count, not its other strings, so that a
    list of untested requirements, or the reason of an expected failure, is not a test of
    them.
    """
    tree = ast.parse(text)
    places = [ast.get_docstring(tree) or ""]
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            places += [node.name, ast.get_docstring(node) or ""]
    places += [
        tok.string
        for tok in tokenize.generate_tokens(io.StringIO(text).readline)
        if tok.type == tokenize.COMMENT
    ]
    return {
        n for place in places for n in re.findall(r"REQ[-_]?(\d{3})", place, flags=re.IGNORECASE)
    }


def mentions(root=ROOT):
    """{REQ id: sorted test files that name it}."""
    out = {}
    for folder in TEST_ROOTS:
        for path in sorted((root / folder).rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            if folder != "evoparam/tests" and "test" not in path.name:
                continue
            for number in _named(path.read_text(encoding="utf-8", errors="replace")):
                out.setdefault(f"REQ-{number}", set()).add(rel)
    return {k: sorted(v) for k, v in out.items()}


def report(root=ROOT):
    """Return the traceability report: each requirement with its test files."""
    spec_text = (root / "docs" / "spec" / "SPEC.md").read_text(encoding="utf-8")
    named = mentions(root)
    rows = []
    for req, section, module, files in matrix(spec_text):
        listed = [_repo_path(f) for f in files]
        rows.append(
            {
                "req": req,
                "section": section,
                "module": module,
                "matrix_test_files": listed,
                "matrix_test_files_missing": [f for f in listed if not (root / f).exists()],
                "tests_naming_it": named.get(req, []),
            }
        )
    untested = [r["req"] for r in rows if not r["tests_naming_it"]]
    return {
        "schema": "evoparam-traceability/1",
        "description": "Requirement -> test traceability of spec §14.2, generated by "
        "tools/gen_traceability.py (REQ-399).",
        "n_requirements": len(rows),
        "n_untested": len(untested),
        "untested": untested,
        "requirements": rows,
    }


def render(root=ROOT):
    """Return the traceability report as JSON text."""
    return json.dumps(report(root), indent=1) + "\n"


def main(argv=None):
    """Write the traceability report; exit 1 when a requirement is untested."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", default=str(ROOT / "dist" / "traceability.json"))
    args = parser.parse_args(argv)
    text = render()
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    data = json.loads(text)
    print(
        f"wrote {out}: {data['n_requirements']} requirements, "
        f"{data['n_untested']} untested {data['untested']}"
    )
    return 1 if data["untested"] else 0


if __name__ == "__main__":
    sys.exit(main())
