"""Write ``docs/api.rst``, the API reference index (spec §9.7, REQ-303 (e)).

One ``autosummary`` table per public module, listing that module's public symbols: the names
in its ``__all__``, or, for a module without ``__all__``, every name that does not start with
an underscore and is not a submodule. The names exported at the package root come first.
``sphinx.ext.autosummary`` (``autosummary_generate = True`` in ``docs/conf.py``) writes one
page per symbol under ``docs/generated/``. ``evoparam/tests/test_docs.py`` checks that every
public symbol is in the index and that the file is up to date (``--check``).

Usage::

    python tools/gen_api_index.py [--check]
"""

import __future__
import argparse
import importlib
import inspect
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "api.rst"
MODULES = ("data", "io", "events", "artifact", "prep", "shapes", "models", "existence",
           "trials", "spatial", "tf", "stats", "hierarchical", "sim", "presets", "reports",
           "plots", "cli", "stream", "benchmark", "utils", "errors", "version")
ROOT_NAMES = ("TrialSet", "Evoked", "Provenance", "load_object", "ResponseModel", "fit",
              "test_response", "read", "reproduce", "detect_events", "selftest", "cite",
              "verbose", "set_log_level", "set_log_file", "__version__")


def public_names(module):
    """Public symbols of ``module``: ``__all__`` or the non-underscore, non-module names."""

    names = getattr(module, "__all__", None)
    if names is None:
        names = [n for n, obj in vars(module).items() if not n.startswith("_")
                 and not inspect.ismodule(obj) and not isinstance(obj, __future__._Feature)]
    return sorted(set(names), key=lambda n: (n.lower(), n))


def public_symbols():
    """{qualified module name: [public names]} for the package root and its public modules."""

    sys.path.insert(0, str(ROOT))
    import evoparam

    out = {"evoparam": [n for n in ROOT_NAMES if hasattr(evoparam, n)]}
    for name in MODULES:
        module = importlib.import_module(f"evoparam.{name}")
        out[f"evoparam.{name}"] = public_names(module)
    return out


def render(symbols):
    lines = ["API reference", "=============", "",
             ".. Generated by tools/gen_api_index.py; do not edit.", "",
             "Every public symbol of evoparam, one table per module. Each name links to its "
             "page (signature, parameters, returns, raises, notes, references, examples).", ""]
    for module, names in symbols.items():
        lines += [f"``{module}``", "-" * (len(module) + 4), "",
                  f".. currentmodule:: {module}", "",
                  ".. autosummary::", "   :toctree: generated/", ""]
        lines += [f"   {n}" for n in names if n != "__version__"]
        lines.append("")
    while lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    text = render(public_symbols())
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            import difflib

            diff = difflib.unified_diff(current.splitlines(True), text.splitlines(True))
            print("".join(list(diff)[:40]), end="")
            print(f"{TARGET.relative_to(ROOT)} is out of date: run tools/gen_api_index.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} "
          f"({sum(len(v) for v in public_symbols().values())} symbols)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
