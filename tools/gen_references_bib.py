"""Write ``docs/references.bib`` from ``docs/spec/LITERATURE.md`` (spec §9.7, REQ-302).

Every numbered reference ``- **[LIT-<axis>-<n>]** <record>`` becomes one ``@misc`` entry
whose key is ``LIT-<axis>-<n>`` (the key the documentation cites with
``sphinxcontrib-bibtex``), with the record as ``note`` and its DOI and first URL when
present. ``evoparam/tests/test_docs.py`` checks that the file is up to date and that every
key cited in the documentation is in it.

Usage::

    python tools/gen_references_bib.py [--check]
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "spec" / "LITERATURE.md"
TARGET = ROOT / "docs" / "references.bib"
ENTRY = re.compile(r"^- \*\*\[(LIT-[a-z]+-\d+)\]\*\*\s*(.+)$", re.MULTILINE)


def _clean(text):
    return re.sub(
        r"\s+", " ", text.replace("{", "(").replace("}", ")").replace("\\", "/").replace("**", "")
    ).strip()


def render(source=SOURCE):
    """Return the BibTeX file built from the reference list ``source``."""
    entries = []
    for key, record in ENTRY.findall(source.read_text(encoding="utf-8")):
        note = _clean(record.split(" — accessed")[0])
        fields = [("note", note)]
        doi = re.search(r"\bDOI:? (10\.\d{4,9}/[^\s,;]+?)\.?(?=[\s,;]|$)", record)
        if doi:
            fields.append(("doi", doi.group(1)))
        url = re.search(r"https?://[^\s,;)]+", record)
        if url:
            fields.append(("url", url.group(0).rstrip(".")))
        body = ",\n".join(f"  {name} = {{{value}}}" for name, value in fields)
        entries.append(f"@misc{{{key},\n{body}\n}}")
    header = (
        "% Generated by tools/gen_references_bib.py from docs/spec/LITERATURE.md; "
        "do not edit by hand.\n\n"
    )
    return header + "\n\n".join(entries) + "\n"


def main(argv=None):
    """Write the BibTeX file, or with ``--check`` exit 1 when it differs."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file differs")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        same = TARGET.is_file() and TARGET.read_text(encoding="utf-8") == text
        print("docs/references.bib is up to date" if same else "docs/references.bib differs")
        return 0 if same else 1
    TARGET.write_text(text, encoding="utf-8")
    print(f"{text.count('@misc')} entries written to {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
