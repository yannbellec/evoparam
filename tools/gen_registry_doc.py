"""Write ``docs/datasets.rst`` from ``evoparam/io/registry.json`` (spec §9.7, REQ-303 (g)).

One row per registered dataset: name, DOI, size, sampling rate, licence, events status and
loader. ``evoparam/tests/test_docs.py`` checks that the page is up to date (``--check``) and
lists every dataset of the registry.

Usage::

    python tools/gen_registry_doc.py [--check]
"""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "evoparam" / "io" / "registry.json"
TARGET = ROOT / "docs" / "datasets.rst"
COLUMNS = ("name", "DOI", "size (GB)", "sampling rate (Hz)", "licence", "events", "loader")


def _cell(value):
    if value is None or value == "":
        return "not stated"
    return str(value).replace("|", "\\|").replace("*", "\\*")


def _number(value):
    if value is None:
        return "not stated"
    return f"{value:g}" if isinstance(value, float) else str(value)


def rows(registry):
    """Return one table row per dataset of the registry."""
    out = []
    for item in registry["datasets"]:
        name = f"``{item['id']}``: {_cell(item.get('title'))}"
        doi = item.get("doi")
        out.append(
            (
                name,
                f"`{doi} <https://doi.org/{doi}>`__" if doi else "not stated",
                _number(item.get("size_gb")),
                _number(item.get("sfreq")),
                _cell(item.get("license")),
                _cell(item.get("events_status")),
                f"``{item['loader']}``" if item.get("loader") else "not stated",
            )
        )
    return out


def render(registry):
    """Return the text of the datasets page built from the registry."""
    lines = [
        "Datasets registry",
        "=================",
        "",
        ".. Generated by tools/gen_registry_doc.py from evoparam/io/registry.json; do not edit.",
        "",
        f"Datasets known to evoparam (registry "
        f"``{registry['schema']}``, version {registry['version']}). "
        f"{registry['description']} ``evoparam.io.list_datasets()`` and "
        "``evoparam.io.dataset_info(name)`` return the same records; files listed in "
        "the registry are downloaded by ``evoparam.io.fetch_*`` and checked against their "
        "SHA-256.",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 30 20 8 10 10 8 14",
        "",
    ]
    lines.append("   * - " + "\n     - ".join(COLUMNS))
    for row in rows(registry):
        lines.append("   * - " + "\n     - ".join(row))
    return "\n".join(lines) + "\n"


def main(argv=None):
    """Write the datasets page, or with ``--check`` fail when it is out of date."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    text = render(json.loads(REGISTRY.read_text(encoding="utf-8")))
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            import difflib

            diff = difflib.unified_diff(current.splitlines(True), text.splitlines(True))
            print("".join(list(diff)[:40]), end="")
            print(f"{TARGET.relative_to(ROOT)} is out of date: run tools/gen_registry_doc.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({text.count('   * - ') - 1} datasets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
